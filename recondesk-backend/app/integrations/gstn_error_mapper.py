"""Shared GSTN error mapper and sanitization utility.

Maps raw Sandbox/GSP API errors and GSTN error codes to clean, provider-agnostic,
CA-facing messages. Ensures that no provider branding ("Sandbox", "sandbox.co.in", etc.)
is ever returned to the frontend or exposed in API responses.

Full raw errors and tracebacks are always preserved in internal logs for debugging.
"""

from __future__ import annotations

import logging
import re
from typing import Any, Optional

import httpx
from fastapi import HTTPException, status

logger = logging.getLogger(__name__)

# Default user-facing fallback when an error is unrecognized
DEFAULT_GENERIC_ERROR_MESSAGE = (
    "Something went wrong while connecting to the GST portal. "
    "Please try again or contact support."
)

# Known clean user-facing messages
MSG_INVALID_GSTIN = "Invalid GSTIN format. Please check and try again."
MSG_OTP_ERROR = "Invalid or expired OTP. Please request a new one."
MSG_SESSION_EXPIRED = "Your session has expired. Please reconnect."
MSG_RATE_LIMIT = "Too many requests. Please try again in a few minutes."
MSG_2B_NOT_FILED = "GSTR-2B is not yet available for this return period."
MSG_2B_STILL_PROCESSING = (
    "GSTR-2B is currently being generated by the GST portal. Please try again shortly."
)
MSG_NETWORK_TIMEOUT = "Unable to connect to the GST portal. Please try again in a few moments."
MSG_PORTAL_UNAVAILABLE = (
    "The GST portal service is temporarily unavailable. Please try again later."
)

# Pattern matchers for known raw error strings (case-insensitive)
_GSTIN_PATTERNS = [
    re.compile(r"invalid\s*gstin\s*pattern", re.I),
    re.compile(r"invalid\s*gstin\s*format", re.I),
    re.compile(r"invalid\s*gstin", re.I),
    re.compile(r"gstin\s*is\s*invalid", re.I),
    re.compile(r"gstin\s*pattern\s*mismatch", re.I),
    re.compile(r"format\s*of\s*gstin\s*is\s*invalid", re.I),
    re.compile(r"missing_gstin", re.I),
]

_OTP_PATTERNS = [
    re.compile(r"invalid\s*otp", re.I),
    re.compile(r"otp\s*expired", re.I),
    re.compile(r"otp\s*has\s*expired", re.I),
    re.compile(r"incorrect\s*otp", re.I),
    re.compile(r"otp\s*verification\s*failed", re.I),
    re.compile(r"max\s*(?:otp\s*)?attempts", re.I),
    re.compile(r"otp\s*not\s*matched", re.I),
    re.compile(r"evc\s*filing\s*requires\s*an\s*otp", re.I),
    re.compile(r"invalid\s*or\s*expired\s*otp", re.I),
]

_SESSION_PATTERNS = [
    re.compile(r"session\s*expired", re.I),
    re.compile(r"token\s*expired", re.I),
    re.compile(r"jwt\s*expired", re.I),
    re.compile(r"invalid\s*token", re.I),
    re.compile(r"invalid\s*session", re.I),
    re.compile(r"unauthorized", re.I),
    re.compile(r"access\s*token\s*expired", re.I),
    re.compile(r"session\s*not\s*found", re.I),
    re.compile(r"no\s*active\s*filing\s*session", re.I),
    re.compile(r"session\s*token\s*expired", re.I),
    re.compile(r"missing\s*access_token", re.I),
    re.compile(r"reconnect\s*via\s*otp", re.I),
    re.compile(r"auth(?:entication)?\s*failed", re.I),
    re.compile(r"http\s*401", re.I),
    re.compile(r"http\s*403", re.I),
]

_RATE_LIMIT_PATTERNS = [
    re.compile(r"rate\s*limit", re.I),
    re.compile(r"too\s*many\s*requests", re.I),
    re.compile(r"quota\s*exceeded", re.I),
    re.compile(r"request\s*limit", re.I),
    re.compile(r"throttle", re.I),
]

_2B_NOT_FILED_PATTERNS = [
    re.compile(r"gstr-?2b\s*not\s*filed", re.I),
    re.compile(r"not\s*filed\s*yet", re.I),
    re.compile(r"ret2b1023", re.I),
]

_2B_STILL_PROCESSING_PATTERNS = [
    re.compile(r"still\s*processing", re.I),
    re.compile(r"still\s*being\s*generated", re.I),
    re.compile(r"ret2b1024", re.I),
]

_TIMEOUT_PATTERNS = [
    re.compile(r"\btime(?:d)?\s+out\b", re.I),
    re.compile(r"\b(?:gateway|request|read|socket|connection|connect)\s*time(?:-)?out\b", re.I),
    re.compile(r"\bconnection\s*(?:refused|reset)\b", re.I),
    re.compile(r"\bconnect(?:ion)?\s*error\b", re.I),
    re.compile(r"\bremote\s*protocol\s*error\b", re.I),
    re.compile(r"\bnetwork\s*error\b", re.I),
]

# Known GSTN Error Codes
_ERROR_CODE_MAP: dict[str, str] = {
    # GSTIN format / validity
    "RET11403": MSG_INVALID_GSTIN,
    "RET11416": MSG_INVALID_GSTIN,
    "ER0001": MSG_INVALID_GSTIN,
    # OTP errors
    "RET11406": MSG_OTP_ERROR,
    "RET11407": MSG_OTP_ERROR,
    "AUTH4037": MSG_OTP_ERROR,
    "AUTH4038": MSG_OTP_ERROR,
    "AUTH5004": MSG_OTP_ERROR,
    # Auth & Session
    "AUTH5001": MSG_SESSION_EXPIRED,
    "AUTH5002": MSG_SESSION_EXPIRED,
    "AUTH5003": MSG_SESSION_EXPIRED,
    "TEC4002": MSG_SESSION_EXPIRED,
    # 2B specific
    "RET2B1023": MSG_2B_NOT_FILED,
    "RET2B1024": MSG_2B_STILL_PROCESSING,
}

# Regex to detect provider brand names in strings (for scrub / defense-in-depth)
_PROVIDER_BRAND_RE = re.compile(r"\b(sandbox(?:\.co\.in)?|sandboxapi|gsp)\b", re.I)


def extract_raw_error_info(
    error: Exception | str | None,
    *,
    error_code: str | None = None,
) -> tuple[str, str | None, int | None]:
    """Extract raw message, error_code, and HTTP status code from an error or exception."""
    raw_msg = ""
    err_cd = error_code
    http_status: int | None = None

    if error is None:
        return "", err_cd, None

    if isinstance(error, str):
        raw_msg = error.strip()
        return raw_msg, err_cd, None

    # Check for known auth / rate limit exception classes by name to avoid tight coupling
    cls_name = error.__class__.__name__
    if "AuthError" in cls_name:
        http_status = status.HTTP_401_UNAUTHORIZED
    elif "RateLimitError" in cls_name:
        http_status = status.HTTP_429_TOO_MANY_REQUESTS

    if isinstance(error, httpx.HTTPStatusError):
        http_status = error.response.status_code
        try:
            body = error.response.json()
            if isinstance(body, dict):
                err = body.get("error")
                if isinstance(err, dict):
                    raw_msg = str(err.get("message") or err.get("msg") or "")
                    if not err_cd:
                        err_cd = err.get("error_cd") or err.get("code")
                elif isinstance(err, str):
                    raw_msg = err
                if not raw_msg:
                    raw_msg = str(body.get("message") or body.get("error") or "")
                if not err_cd and isinstance(body.get("error_cd"), str):
                    err_cd = body.get("error_cd")
        except Exception:
            raw_msg = error.response.text[:300] if error.response else ""

        if not raw_msg:
            raw_msg = str(error)

        return raw_msg, str(err_cd).strip() if err_cd else None, http_status

    if isinstance(error, httpx.TimeoutException):
        return str(error), err_cd, status.HTTP_504_GATEWAY_TIMEOUT

    if isinstance(error, (httpx.ConnectError, httpx.NetworkError)):
        return str(error), err_cd, status.HTTP_503_SERVICE_UNAVAILABLE

    # Custom filing / GST client exceptions
    if hasattr(error, "error_cd") and getattr(error, "error_cd"):
        err_cd = str(getattr(error, "error_cd"))

    if hasattr(error, "status_code") and isinstance(getattr(error, "status_code"), int):
        http_status = getattr(error, "status_code")

    if hasattr(error, "message") and getattr(error, "message"):
        raw_msg = str(getattr(error, "message"))
    else:
        raw_msg = str(error)

    return raw_msg, str(err_cd).strip() if err_cd else None, http_status


def map_gstn_error(
    error: Exception | str | None,
    *,
    error_code: str | None = None,
    default_message: str | None = None,
    log_context: str | None = None,
) -> str:
    """Map raw GSTN / GSP error to a clean, user-friendly, provider-agnostic string.

    Guarantees:
    - Never returns raw Provider strings (e.g. "Sandbox GST API request failed...").
    - Never contains the word "Sandbox" or other GSP names.
    - Unrecognized errors fall back to a safe generic message.
    - Logs the full raw error for internal debugging.
    """
    raw_msg, err_cd, http_status = extract_raw_error_info(error, error_code=error_code)

    # Log full details internally
    if raw_msg or err_cd:
        ctx_prefix = f"[{log_context}] " if log_context else ""
        logger.warning(
            "%sGSTN error intercepted: raw_msg=%r error_code=%r http_status=%r",
            ctx_prefix,
            raw_msg,
            err_cd,
            http_status,
        )

    # 1. Match on error code if known
    if err_cd and str(err_cd).strip().upper() in _ERROR_CODE_MAP:
        return _ERROR_CODE_MAP[str(err_cd).strip().upper()]

    # 2. Match on HTTP status codes
    if http_status == 429:
        return MSG_RATE_LIMIT
    if http_status in (401, 403):
        return MSG_SESSION_EXPIRED
    if http_status == 504:
        return MSG_NETWORK_TIMEOUT

    # 3. Match against known regex patterns
    test_str = f"{raw_msg} {err_cd or ''}"

    for p in _GSTIN_PATTERNS:
        if p.search(test_str):
            return MSG_INVALID_GSTIN

    for p in _OTP_PATTERNS:
        if p.search(test_str):
            return MSG_OTP_ERROR

    for p in _SESSION_PATTERNS:
        if p.search(test_str):
            return MSG_SESSION_EXPIRED

    for p in _RATE_LIMIT_PATTERNS:
        if p.search(test_str):
            return MSG_RATE_LIMIT

    for p in _2B_NOT_FILED_PATTERNS:
        if p.search(test_str):
            return MSG_2B_NOT_FILED

    for p in _2B_STILL_PROCESSING_PATTERNS:
        if p.search(test_str):
            return MSG_2B_STILL_PROCESSING

    for p in _TIMEOUT_PATTERNS:
        if p.search(test_str):
            return MSG_NETWORK_TIMEOUT

    # 4. Fallback: return default message (or generic fallback)
    fallback = default_message or DEFAULT_GENERIC_ERROR_MESSAGE

    # Safety scrub: ensure fallback never has provider names
    if _PROVIDER_BRAND_RE.search(fallback):
        return DEFAULT_GENERIC_ERROR_MESSAGE

    return fallback


def sanitize_message_text(text: str | None) -> str:
    """Scrub any accidental mention of GSP provider from any string."""
    if not text:
        return DEFAULT_GENERIC_ERROR_MESSAGE
    if _PROVIDER_BRAND_RE.search(text):
        return map_gstn_error(text)
    return text


def to_http_status_code(
    error: Exception | str | None,
    *,
    error_code: str | None = None,
    default_status: int = status.HTTP_502_BAD_GATEWAY,
) -> int:
    """Determine the most appropriate HTTP status code for a GSTN error."""
    raw_msg, err_cd, http_status = extract_raw_error_info(error, error_code=error_code)

    if http_status and http_status in (400, 401, 403, 404, 409, 422, 429, 502, 503, 504):
        # Translate 404 from external GSP into 502 so clients do not think the backend route was 404
        if http_status == 404:
            return status.HTTP_502_BAD_GATEWAY
        return http_status

    msg = map_gstn_error(error, error_code=error_code)
    if msg == MSG_SESSION_EXPIRED:
        return status.HTTP_401_UNAUTHORIZED
    if msg == MSG_RATE_LIMIT:
        return status.HTTP_429_TOO_MANY_REQUESTS
    if msg == MSG_INVALID_GSTIN:
        return status.HTTP_422_UNPROCESSABLE_ENTITY
    if msg in (MSG_NETWORK_TIMEOUT, MSG_PORTAL_UNAVAILABLE):
        return status.HTTP_503_SERVICE_UNAVAILABLE

    return default_status


def gstn_http_exception(
    error: Exception | str | None,
    *,
    error_code: str | None = None,
    default_status_code: int = status.HTTP_502_BAD_GATEWAY,
    context: str | None = None,
    include_error_cd: bool = False,
) -> HTTPException:
    """Create a FastAPI HTTPException with a clean, sanitized message and correct status code.

    Guaranteed never to contain raw provider strings.
    """
    raw_msg, err_cd, _ = extract_raw_error_info(error, error_code=error_code)
    status_code = to_http_status_code(
        error, error_code=err_cd, default_status=default_status_code
    )
    clean_message = map_gstn_error(
        error,
        error_code=err_cd,
        log_context=context,
    )

    if include_error_cd:
        detail: Any = {
            "message": clean_message,
            "error_cd": err_cd,
        }
    else:
        detail = clean_message

    return HTTPException(status_code=status_code, detail=detail)
