"""Excel (xlsx) builder for Advanced Export — detail + summary sheets."""

from __future__ import annotations

import io

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill
from openpyxl.utils import get_column_letter

from app.services.advanced_export_service import (
    AdvancedExportBundle,
    AdvancedExportRow,
    export_filename,
    summarize_rows,
)

_HEADER_BLUE = "1F4E79"
_HEADER_GREEN = "375623"


def _rs(n: float) -> str:
    return f"Rs {int(round(float(n))):,}"


DETAIL_HEADERS = (
    "Status",
    "Client ID",
    "Period",
    "ITC Eligibility",
    "Invoice Number",
    "Vendor Name",
    "Supplier GSTIN",
    "Invoice Date",
    "Taxable Value",
    "ITC Amount",
    "Match Level",
    "WHAT",
    "WHY",
    "NEXT",
)


def build_advanced_export_xlsx_bytes(
    bundle: AdvancedExportBundle,
    rows: list[AdvancedExportRow],
) -> tuple[bytes, str]:
    """Return (xlsx bytes, filename) with Sheet1=detail, Sheet2=summary."""
    wb = Workbook()
    default = wb.active
    wb.remove(default)

    ws1 = wb.create_sheet("Detail", 0)
    hdr_fill = PatternFill("solid", fgColor=_HEADER_BLUE)
    hdr_font = Font(bold=True, color="FFFFFF")
    for col, h in enumerate(DETAIL_HEADERS, 1):
        c = ws1.cell(row=1, column=col, value=h)
        c.font = hdr_font
        c.fill = hdr_fill

    for i, row in enumerate(rows, 2):
        vals = (
            row.status,
            row.client_id,
            row.period,
            row.itc_eligibility_category,
            row.invoice_number,
            row.vendor_name,
            row.supplier_gstin,
            row.invoice_date,
            round(row.taxable_value, 2),
            round(row.itc_amount, 2),
            row.match_level,
            row.decision_what or "—",
            row.decision_why or "—",
            row.decision_next or "—",
        )
        for col, v in enumerate(vals, 1):
            ws1.cell(row=i, column=col, value=v)

    for col in range(1, len(DETAIL_HEADERS) + 1):
        ws1.column_dimensions[get_column_letter(col)].width = 16
    ws1.column_dimensions["F"].width = 24
    ws1.column_dimensions["L"].width = 36
    ws1.column_dimensions["M"].width = 36
    ws1.column_dimensions["N"].width = 36

    ws2 = wb.create_sheet("Summary", 1)
    title_font = Font(size=14, bold=True, color=_HEADER_BLUE)
    ws2["A1"] = "Advanced Export Summary"
    ws2["A1"].font = title_font
    ws2["A3"] = "Client:"
    ws2["B3"] = bundle.client_name or "—"
    ws2["A4"] = "Period:"
    ws2["B4"] = bundle.period or "—"
    ws2["A5"] = "Generated:"
    ws2["B5"] = bundle.generated_at.strftime("%d %b %Y %H:%M UTC")
    if bundle.generated_by:
        ws2["A6"] = "Generated by:"
        ws2["B6"] = bundle.generated_by

    summary = summarize_rows(rows)
    start = 8
    ws2.cell(row=start, column=1, value="Count by Status").font = Font(bold=True)
    ws2.cell(row=start, column=1).fill = PatternFill("solid", fgColor=_HEADER_GREEN)
    ws2.cell(row=start, column=1).font = Font(bold=True, color="FFFFFF")
    ws2.cell(row=start, column=2, value="Count").font = Font(bold=True, color="FFFFFF")
    ws2.cell(row=start, column=2).fill = PatternFill("solid", fgColor=_HEADER_GREEN)
    r = start + 1
    for status, count in summary["count_by_status"].items():
        ws2.cell(row=r, column=1, value=status)
        ws2.cell(row=r, column=2, value=count)
        r += 1
    ws2.cell(row=r, column=1, value="Total rows")
    ws2.cell(row=r, column=1).font = Font(bold=True)
    ws2.cell(row=r, column=2, value=summary["total_rows"])
    r += 2

    ws2.cell(row=r, column=1, value="Count by ITC Eligibility").font = Font(
        bold=True, color="FFFFFF"
    )
    ws2.cell(row=r, column=1).fill = PatternFill("solid", fgColor=_HEADER_BLUE)
    ws2.cell(row=r, column=2, value="Count").font = Font(bold=True, color="FFFFFF")
    ws2.cell(row=r, column=2).fill = PatternFill("solid", fgColor=_HEADER_BLUE)
    r += 1
    for cat, count in summary["count_by_itc_category"].items():
        ws2.cell(row=r, column=1, value=cat)
        ws2.cell(row=r, column=2, value=count)
        r += 1
    r += 1

    ws2.cell(row=r, column=1, value="Total ITC at Risk (Rs)")
    ws2.cell(row=r, column=1).font = Font(bold=True)
    ws2.cell(row=r, column=2, value=_rs(summary["total_itc_at_risk"]))
    r += 1
    ws2.cell(row=r, column=1, value="Total Missed ITC (Rs)")
    ws2.cell(row=r, column=1).font = Font(bold=True)
    ws2.cell(row=r, column=2, value=_rs(summary["total_missed_itc"]))

    ws2.column_dimensions["A"].width = 32
    ws2.column_dimensions["B"].width = 22

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue(), export_filename(bundle, "xlsx")
