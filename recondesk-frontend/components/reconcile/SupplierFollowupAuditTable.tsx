"use client";

import { useState } from "react";
import { X } from "lucide-react";
import {
  filterDropdownClass,
  filterRowClass,
  tableCellClass,
  tableClass,
  tableHeadCellClass,
  tableHeadClass,
  tableRowClass,
  tableWrapClass,
} from "@/components/reconcile/ResultsUi";
import {
  formatFollowupAuditStatus,
  formatFollowupAuditTimeIst,
  formatFollowupTemplateType,
  type SupplierFollowupAuditRow,
} from "@/lib/followupAudit";

function FollowupLetterViewModal({
  row,
  onClose,
}: {
  row: SupplierFollowupAuditRow;
  onClose: () => void;
}) {
  const body = row.letter_body?.trim() || "";
  return (
    <div
      className="fixed inset-0 z-[100] flex items-center justify-center bg-black/40 p-4"
      role="dialog"
      aria-modal="true"
      aria-labelledby="followup-letter-view-title"
    >
      <div className="flex max-h-[90vh] w-full max-w-2xl flex-col overflow-hidden rounded-2xl border border-[#F0F0F0] bg-white shadow-xl">
        <div className="flex items-center justify-between border-b border-[#F0F0F0] px-5 py-4">
          <div>
            <h2
              id="followup-letter-view-title"
              className="text-lg font-semibold text-gray-900"
            >
              Saved follow-up letter
            </h2>
            <p className="mt-0.5 text-[12px] text-gray-500">
              {row.supplier_name_display?.trim() || row.supplier_gstin} ·{" "}
              {formatFollowupAuditStatus(row.status)} ·{" "}
              {formatFollowupAuditTimeIst(row.generated_at)}
            </p>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="rounded-lg p-1 text-gray-500 hover:bg-gray-100"
            aria-label="Close"
          >
            <X className="h-5 w-5" />
          </button>
        </div>
        <div className="min-h-0 flex-1 overflow-y-auto px-5 py-4">
          {body ? (
            <pre className="whitespace-pre-wrap font-mono text-[12px] leading-relaxed text-gray-800">
              {body}
            </pre>
          ) : (
            <p className="text-[13px] text-gray-500">
              No letter body was stored for this audit entry (legacy record).
            </p>
          )}
        </div>
        <div className="flex justify-end border-t border-[#F0F0F0] px-5 py-4">
          <button
            type="button"
            onClick={onClose}
            className="rounded-xl border border-[#E5E7EB] bg-white px-4 py-2 text-[13px] font-medium text-gray-700 hover:bg-gray-50"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
}

export function SupplierFollowupAuditTable({
  rows,
  showTaxPeriod = false,
  emptyMessage,
}: {
  rows: SupplierFollowupAuditRow[];
  showTaxPeriod?: boolean;
  emptyMessage: string;
}) {
  const [viewRow, setViewRow] = useState<SupplierFollowupAuditRow | null>(null);

  if (rows.length === 0) {
    return (
      <p className="py-8 text-center text-[13px] text-gray-500">{emptyMessage}</p>
    );
  }

  return (
    <>
      <div className={tableWrapClass}>
        <table className={tableClass}>
          <thead className={tableHeadClass}>
            <tr>
              <th className={tableHeadCellClass}>Supplier Name</th>
              <th className={tableHeadCellClass}>Supplier GSTIN</th>
              {showTaxPeriod ? (
                <th className={tableHeadCellClass}>Tax Period</th>
              ) : null}
              <th className={tableHeadCellClass}>Template Type</th>
              <th className={tableHeadCellClass}>Status</th>
              <th className={tableHeadCellClass}>Generated By</th>
              <th className={tableHeadCellClass}>Time</th>
              <th className={tableHeadCellClass}>Letter</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((row) => (
              <tr key={row.id} className={tableRowClass}>
                <td className={tableCellClass}>
                  {row.supplier_name_display?.trim() || "—"}
                </td>
                <td className={`${tableCellClass} font-mono text-[12px] text-gray-500`}>
                  {row.supplier_gstin}
                </td>
                {showTaxPeriod ? (
                  <td className={tableCellClass}>{row.tax_period}</td>
                ) : null}
                <td className={tableCellClass}>
                  {formatFollowupTemplateType(row.template_type)}
                </td>
                <td className={tableCellClass}>
                  {formatFollowupAuditStatus(row.status)}
                </td>
                <td className={tableCellClass}>
                  {row.generated_by_name?.trim() || "—"}
                </td>
                <td className={`${tableCellClass} text-[13px] text-gray-600`}>
                  {formatFollowupAuditTimeIst(row.generated_at)}
                </td>
                <td className={tableCellClass}>
                  {row.letter_body?.trim() ? (
                    <button
                      type="button"
                      onClick={() => setViewRow(row)}
                      className="text-[13px] font-medium text-brand hover:underline"
                    >
                      View
                    </button>
                  ) : (
                    <span className="text-[12px] text-gray-400">—</span>
                  )}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      {viewRow ? (
        <FollowupLetterViewModal row={viewRow} onClose={() => setViewRow(null)} />
      ) : null}
    </>
  );
}

export function FollowupAuditFilters({
  status,
  onStatusChange,
  supplierGstin,
  onSupplierGstinChange,
  supplierGstinOptions,
  taxPeriod,
  onTaxPeriodChange,
  taxPeriodOptions,
}: {
  status: string;
  onStatusChange: (v: string) => void;
  supplierGstin?: string;
  onSupplierGstinChange?: (v: string) => void;
  supplierGstinOptions?: string[];
  taxPeriod?: string;
  onTaxPeriodChange?: (v: string) => void;
  taxPeriodOptions?: string[];
}) {
  return (
    <div className={`${filterRowClass} mb-4 items-center`}>
      <select
        className={filterDropdownClass}
        value={status}
        onChange={(e) => onStatusChange(e.target.value)}
        aria-label="Filter by status"
      >
        <option value="">All statuses</option>
        <option value="generated">Generated</option>
        <option value="downloaded">Downloaded</option>
        <option value="copied">Copied</option>
      </select>
      {onSupplierGstinChange != null && supplierGstinOptions != null ? (
        <select
          className={filterDropdownClass}
          value={supplierGstin ?? ""}
          onChange={(e) => onSupplierGstinChange(e.target.value)}
          aria-label="Filter by supplier GSTIN"
        >
          <option value="">All suppliers</option>
          {supplierGstinOptions.map((g) => (
            <option key={g} value={g}>
              {g}
            </option>
          ))}
        </select>
      ) : null}
      {onTaxPeriodChange != null && taxPeriodOptions != null ? (
        <select
          className={filterDropdownClass}
          value={taxPeriod ?? ""}
          onChange={(e) => onTaxPeriodChange(e.target.value)}
          aria-label="Filter by tax period"
        >
          <option value="">All tax periods</option>
          {taxPeriodOptions.map((p) => (
            <option key={p} value={p}>
              {p}
            </option>
          ))}
        </select>
      ) : null}
    </div>
  );
}
