/**
 * Draw a right-aligned bold total line. If the current Y would overflow into
 * the footer zone, add a new page first. Returns the next Y after the line.
 */
function drawTotalLine(
  doc: jsPDF,
  label: string,
  value: number,
  y: number
): number {
  const pageHeight = doc.internal.pageSize.height;
  const FOOTER_ZONE = pageHeight - 20;
  if (y > FOOTER_ZONE) {
    doc.addPage();
    y = 30;
  }
  const formatted =
    typeof value === "number" && !Number.isNaN(value)
      ? formatINR(Math.round(Math.abs(value))) + (value < 0 ? " (CR)" : "")
      : "-";
  setFont(doc, "bold");
  doc.setFontSize(9);
  setInk(doc);
  doc.text(`${label}: ${formatted}`, 190, y, { align: "right" });
  setFont(doc, "normal");
  setCharcoal(doc);
  return y + 8;
}

