export function reportPdfFilename(gstin: string, period: string): string {
  const safeGstin = (gstin || "client").replace(/[^A-Za-z0-9]/g, "").toUpperCase();
  const safePeriod = (period || "period").replace(/[^A-Za-z0-9-]/g, "");
  return `ReconDesk-Report-${safeGstin}-${safePeriod}.pdf`;
}

export function formatReportPeriod(period: string): string {
  const m = period.match(/^(\d{4})-(\d{2})$/);
  if (!m) return period || "—";
  const d = new Date(Number(m[1]), Number(m[2]) - 1, 1);
  if (Number.isNaN(d.getTime())) return period;
  return d.toLocaleString("en-IN", { month: "long", year: "numeric" });
}

function formatReportDateIst(date = new Date()): string {
  return date.toLocaleString("en-IN", {
    timeZone: "Asia/Kolkata",
    day: "numeric",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

function formatShortDateIst(iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return "—";
  return d.toLocaleString("en-IN", {
    timeZone: "Asia/Kolkata",
    day: "numeric",
    month: "short",
    year: "numeric",
  });
}

function formatStatusLabel(status: string): string {
  const s = (status || "").trim();
  if (!s) return "—";
  return s.charAt(0).toUpperCase() + s.slice(1).toLowerCase();
}

function readNumericField(
  data: Record<string, string | number>,
  keys: string[]
): number | null {
  for (const k of keys) {
    const v = data[k];
    if (v == null || v === "") continue;
    const n = Number(v);
    if (Number.isFinite(n)) return n;
  }
  return null;
}

function rule37DeadlineInfo(invoiceDate: string): {
  deadline: Date | null;
  daysLeft: number | null;
  deadlineLabel: string;
} {
  const d = new Date(invoiceDate);
  if (Number.isNaN(d.getTime())) {
    return { deadline: null, daysLeft: null, deadlineLabel: "—" };
  }
  const deadline = new Date(d);
  deadline.setDate(deadline.getDate() + 180);
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const dl = new Date(deadline);
  dl.setHours(0, 0, 0, 0);
  const daysLeft = Math.ceil((dl.getTime() - today.getTime()) / 86_400_000);
  return {
    deadline,
    daysLeft,
    deadlineLabel: formatShortDateIst(deadline.toISOString()),
  };
}

function rule37StatusLabel(row: ReportReconcileRow): string {
  if (row.rule37_action_status === "resolved") {
    return row.rule37_payment_coverage === "partial"
      ? "Partial Settlement"
      : "Marked as Settled";
  }
  if (row.rule37_action_status === "acknowledged") return "ITC Reversed";
  const u = row.rule37_urgency;
  if (u === "CRITICAL") return "Overdue";
  if (u === "HIGH") return "Urgent";
  if (u === "MEDIUM") return "Pending";
  return "Pending";
}

function topRowsByAmount<T extends { amount: number }>(rows: T[], max: number): T[] {
  return [...rows].sort((a, b) => b.amount - a.amount).slice(0, max);
}

