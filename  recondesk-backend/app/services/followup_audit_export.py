"""Excel export for client-level supplier follow-up audit history."""

from __future__ import annotations

import io
import re
from datetime import datetime
from typing import Any
from zoneinfo import ZoneInfo

from openpyxl import Workbook
from openpyxl.styles import Font

_IST = ZoneInfo("Asia/Kolkata")

_TEMPLATE_LABELS = {
    "wrongful_itc_single": "Wrongful ITC (single)",
    "wrongful_itc_bulk": "Wrongful ITC (bulk)",
}

_STATUS_LABELS = {
    "generated": "Generated",
    "downloaded": "Downloaded",
    "copied": "Copied",
}


def _format_ist(iso_ts: str) -> str:
    raw = (iso_ts or "").strip()
    if not raw:
        return "—"
    try:
        dt = datetime.fromisoformat(raw.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=ZoneInfo("UTC"))
        local = dt.astimezone(_IST)
        return local.strftime("%d %b %Y, %I:%M %p IST")
    except (ValueError, TypeError):
        return raw


def _safe_xlsx_filename_gstin(gstin: str) -> str:
    safe = re.sub(r"[^A-Za-z0-9]", "", (gstin or "client").upper()) or "client"
    return f"followup-history-{safe}.xlsx"


def build_followup_history_xlsx_bytes(
    rows: list[dict[str, Any]],
    *,
    client_gstin: str,
    include_tax_period: bool = True,
) -> tuple[bytes, str]:
    wb = Workbook()
    ws = wb.active
    ws.title = "Follow-up History"

    headers = [
        "Supplier Name",
        "Supplier GSTIN",
        "Template Type",
        "Status",
        "Generated By",
        "Time (IST)",
    ]
    if include_tax_period:
        headers.insert(2, "Tax Period")

    ws.append(headers)
    for cell in ws[1]:
        cell.font = Font(bold=True)

    for row in rows:
        template = _TEMPLATE_LABELS.get(
            str(row.get("template_type") or ""),
            str(row.get("template_type") or "—"),
        )
        status = _STATUS_LABELS.get(
            str(row.get("status") or ""),
            str(row.get("status") or "—"),
        )
        line = [
            str(row.get("supplier_name_display") or "—"),
            str(row.get("supplier_gstin") or "—"),
        ]
        if include_tax_period:
            line.append(str(row.get("tax_period") or "—"))
        line.extend(
            [
                template,
                status,
                str(row.get("generated_by_name") or "—"),
                _format_ist(str(row.get("generated_at") or "")),
            ]
        )
        ws.append(line)

    for col in ws.columns:
        letter = col[0].column_letter
        max_len = max(len(str(c.value or "")) for c in col)
        ws.column_dimensions[letter].width = min(max(max_len + 2, 12), 40)

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue(), _safe_xlsx_filename_gstin(client_gstin)
